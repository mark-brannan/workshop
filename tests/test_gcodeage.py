import subprocess
import zipfile
from datetime import datetime
from io import BytesIO
from pathlib import Path

from shop import gcodeage

HEADER = "; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.5.2 on {} at {}\n; total layer number: 100\n"


def cube_3mf(size: float, settings: bool = False) -> bytes:
    """A closed cube as a minimal 3MF; ``settings`` adds a slicer project file, which must not count as a shape change."""
    s = size
    v = [(x, y, z) for x in (0, s) for y in (0, s) for z in (0, s)]
    t = [(0, 2, 1), (1, 2, 3), (4, 5, 6), (5, 7, 6), (0, 1, 4), (1, 5, 4), (2, 6, 3), (3, 6, 7), (0, 4, 2), (2, 4, 6), (1, 3, 5), (3, 7, 5)]
    mesh = "<mesh><vertices>" + "".join(f'<vertex x="{x}" y="{y}" z="{z}"/>' for x, y, z in v) + "</vertices><triangles>" + \
        "".join(f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in t) + "</triangles></mesh>"
    out = BytesIO()
    with zipfile.ZipFile(out, "w") as z:
        z.writestr("3D/3dmodel.model", f"<model><resources><object id=\"1\">{mesh}</object></resources></model>")
        if settings:
            z.writestr("Metadata/project_settings.config", "{}")
    return out.getvalue()


def commit(root: Path, data: bytes, msg: str, when: str) -> None:
    p = root / "projects/box/out/box_scad.3mf"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data)
    env = {"GIT_AUTHOR_DATE": when, "GIT_COMMITTER_DATE": when, "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t",
           "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@t", "PATH": "/usr/bin:/bin"}
    subprocess.run(["git", "-C", str(root), "add", "."], check=True, env=env)
    subprocess.run(["git", "-C", str(root), "commit", "-qm", msg], check=True, env=env)


def repo(tmp_path: Path) -> Path:
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    commit(tmp_path, cube_3mf(10), "first shape", "2026-11-20T10:00:00")
    commit(tmp_path, cube_3mf(12), "slits added", "2026-11-25T14:37:00")
    commit(tmp_path, cube_3mf(12, settings=True), "Slicer settings", "2026-11-25T15:00:00")
    return tmp_path


def local(iso: str) -> datetime:
    return datetime.fromisoformat(iso)


def test_reads_the_slice_time_from_the_orca_header():
    assert gcodeage.sliced_at(HEADER.format("2026-11-23", "14:48:37")) == local("2026-11-23T14:48:37")
    assert gcodeage.sliced_at("; no header here") is None


def test_gcode_maps_to_the_longest_matching_3mf(tmp_path):
    out = tmp_path / "projects/sump/out"
    out.mkdir(parents=True)
    for n in ("sump_scad.3mf", "sump_scad_lid.3mf"):
        (out / n).write_bytes(b"")
    assert gcodeage.model_for("sump_scad_PETG_2h6m.gcode", tmp_path).name == "sump_scad.3mf"
    assert gcodeage.model_for("sump_scad_draft_PETG_1h9m.gcode", tmp_path).name == "sump_scad.3mf"
    assert gcodeage.model_for("sump_scad_lid_PETG_9m.gcode", tmp_path).name == "sump_scad_lid.3mf"
    assert gcodeage.model_for("petg-2026-11-24.gcode", tmp_path) is None


def test_a_settings_save_is_not_a_shape_change(tmp_path):
    root = repo(tmp_path)
    change = gcodeage.last_change(root / "projects/box/out/box_scad.3mf", root)
    assert "slits added" in change.what


def test_gcode_sliced_before_the_shape_change_warns(tmp_path):
    root = repo(tmp_path)
    level, text = gcodeage.verdict("box_scad_PETG_2h6m.gcode", HEADER.format("2026-11-23", "14:48:37"), root)
    assert level == "WARN" and "STALE GCODE" in text and "slits added" in text


def test_gcode_sliced_after_the_shape_change_is_ok(tmp_path):
    root = repo(tmp_path)
    level, _ = gcodeage.verdict("box_scad_PETG_2h6m.gcode", HEADER.format("2026-11-25", "14:50:00"), root)
    assert level == "ok"


def test_an_uncommitted_shape_edit_counts_as_newer_than_any_slice(tmp_path):
    root = repo(tmp_path)
    (root / "projects/box/out/box_scad.3mf").write_bytes(cube_3mf(14))
    level, text = gcodeage.verdict("box_scad_PETG_2h6m.gcode", HEADER.format("2026-11-26", "09:00:00"), root)
    assert level == "WARN" and "uncommitted" in text


def test_a_gcode_with_no_model_is_a_note_not_a_warning(tmp_path):
    root = repo(tmp_path)
    level, _ = gcodeage.verdict("petg-2026-11-24.gcode", HEADER.format("2026-11-24", "09:00:00"), root)
    assert level == "note"


def two_cubes_3mf(a: float, b: float) -> bytes:
    """Two bodies in one 3MF, as the separate objects shop build writes."""
    one, two = cube_3mf(a), cube_3mf(b)
    out = BytesIO()
    with zipfile.ZipFile(out, "w") as z:
        for i, data in enumerate((one, two)):
            z.writestr(f"3D/Objects/part_{i}.model", zipfile.ZipFile(BytesIO(data)).read("3D/3dmodel.model"))
        z.writestr("3D/3dmodel.model", "<model/>")
    return out.getvalue()


def test_bodies_removed_from_the_plate_in_the_slicer_are_not_a_shape_change(tmp_path):
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    commit(tmp_path, two_cubes_3mf(10, 12), "two clips", "2026-11-25T20:00:00")
    commit(tmp_path, cube_3mf(12, settings=True), "Slicer settings", "2026-11-25T21:05:00")
    level, _ = gcodeage.verdict("box_scad_PETG_1h.gcode", HEADER.format("2026-11-25", "21:04:00"), tmp_path)
    assert level == "ok"


def test_a_body_grown_on_a_plate_still_warns(tmp_path):
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    commit(tmp_path, two_cubes_3mf(10, 12), "two clips", "2026-11-25T20:00:00")
    commit(tmp_path, two_cubes_3mf(10, 13), "one clip longer", "2026-11-25T22:00:00")
    level, _ = gcodeage.verdict("box_scad_PETG_1h.gcode", HEADER.format("2026-11-25", "21:04:00"), tmp_path)
    assert level == "WARN"
