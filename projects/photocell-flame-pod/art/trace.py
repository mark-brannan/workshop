"""Trace fire-glyph.png into fire-glyph.scad: the glyph's contours, height 1, centred on its bounding box, tip at +Y.

Run: uv run python projects/photocell-flame-pod/art/trace.py
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from PIL import Image
from scipy.ndimage import gaussian_filter
from shapely.geometry import Polygon

HERE = Path(__file__).parent
a = np.asarray(Image.open(HERE / "fire-glyph.png").convert("RGBA")).astype(int)
sat = a[..., :3].max(-1) - a[..., :3].min(-1)
mask = gaussian_filter(((sat > 60) & (a[..., 3] > 128)).astype(float), 1.5)
cs = plt.contour(np.pad(mask, 2), levels=[0.5])
rings = [Polygon(p - 2) for p in cs.allsegs[0] if len(p) > 20]
rings = [r.simplify(0.8) for r in rings if r.area > 200]
(x0, y0, x1, y1) = Polygon(max(rings, key=lambda r: r.area).exterior).bounds
h = y1 - y0
out = ["// Generated by trace.py from fire-glyph.png; do not edit. Height 1, centred, tip at +Y.",
       f"fire_glyph_aspect = {(x1 - x0) / h:.4f};  // width over height", "fire_glyph_paths = ["]
TONGUE_SHIFT = 0.04  # of the glyph's height (0.7 mm at 18 long): left tongue up, right tongue down (owner, 2026-11-25)


def shift_tongue(pts, valley, outer, dy, ramp=4):
    """Slide the points from the valley beside a side tongue round its tip to a point on its outer edge by dy, eased to 0 at both ends."""
    near = lambda q: int(np.argmin(np.hypot(*(pts - q).T)))
    i, j = sorted((near(valley), near(outer)))
    for k in range(i, j + 1):
        t = min(k - i, j - k) / ramp
        pts[k, 1] += dy * (3 * min(t, 1) ** 2 - 2 * min(t, 1) ** 3)


for r in rings:
    pts = np.array(r.exterior.coords)[:-1]
    pts = np.c_[(pts[:, 0] - (x0 + x1) / 2) / h, -(pts[:, 1] - (y0 + y1) / 2) / h]
    shift_tongue(pts, (-0.2665, -0.0416), (-0.3659, -0.0955), TONGUE_SHIFT)
    shift_tongue(pts, (0.2009, -0.1036), (0.3659, -0.0906), -TONGUE_SHIFT)
    out.append("    [" + ", ".join(f"[{x:.4f}, {y:.4f}]" for x, y in pts) + "],")
out.append("];")
(HERE / "fire-glyph.scad").write_text("\n".join(out) + "\n")
print(len(rings), [len(r.exterior.coords) for r in rings])
