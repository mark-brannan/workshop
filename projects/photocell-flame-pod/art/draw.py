"""Draw the fire glyph from scratch into fire-glyph.scad: height 1, centred on its bounding box, tip at +Y.

Built from a base circle, two bezier flanks, two side licks and an inner teardrop notch; no image is traced.
Run: uv run python projects/photocell-flame-pod/art/draw.py
"""

from pathlib import Path

import numpy as np
from shapely import affinity
from shapely.geometry import Point, Polygon
from shapely.ops import unary_union

HERE = Path(__file__).parent


def bez(p0, p1, p2, p3, n=40):
    t = np.linspace(0, 1, n)[:, None]
    return (1 - t) ** 3 * p0 + 3 * (1 - t) ** 2 * t * p1 + 3 * (1 - t) * t**2 * p2 + t**3 * p3


def teardrop(cx, cy, r, tip_y, lean=0.0):
    """Circle of radius r at (cx, cy) with a tip at (cx + lean, tip_y), flanks tangent to the circle's sides."""
    tip = np.array([cx + lean, tip_y])
    left = bez(np.array([cx - r, cy]), np.array([cx - r, cy + (tip_y - cy) * 0.55]), np.array([cx + lean * 0.4, cy + (tip_y - cy) * 0.7]), tip)
    right = bez(tip, np.array([cx + lean * 0.4 + r * 0.2, cy + (tip_y - cy) * 0.6]), np.array([cx + r, cy + (tip_y - cy) * 0.4]), np.array([cx + r, cy]))
    return unary_union([Point(cx, cy).buffer(r, 64), Polygon(np.vstack([left, right]))])


body = teardrop(0.0, -0.18, 0.34, 0.66, lean=-0.10)
lick_l = affinity.rotate(teardrop(0, 0, 0.08, 0.30), 16, origin=(0, 0))
lick_r = affinity.rotate(teardrop(0, 0, 0.055, 0.16), -22, origin=(0, 0))
body = unary_union([body, affinity.translate(lick_l, -0.29, -0.06), affinity.translate(lick_r, 0.31, -0.20)])
notch = unary_union([teardrop(0.02, -0.38, 0.15, 0.00, lean=0.03), Polygon([(-0.13, -0.38), (0.17, -0.38), (0.17, -0.9), (-0.13, -0.9)])])
glyph = body.difference(notch).buffer(0.01).buffer(-0.01).simplify(0.002)

x0, y0, x1, y1 = glyph.bounds
h = y1 - y0
pts = np.array(glyph.exterior.coords)[:-1]
pts = np.c_[(pts[:, 0] - (x0 + x1) / 2) / h, (pts[:, 1] - (y0 + y1) / 2) / h]
if (pts[:, 0] * np.roll(pts[:, 1], -1) - np.roll(pts[:, 0], -1) * pts[:, 1]).sum() < 0:
    pts = pts[::-1]
assert len(glyph.interiors) == 0
out = ["// Generated by draw.py; do not edit. Height 1, centred, tip at +Y.",
       f"fire_glyph_aspect = {(x1 - x0) / h:.4f};  // width over height", "fire_glyph_paths = [",
       "    [" + ", ".join(f"[{x:.4f}, {y:.4f}]" for x, y in pts) + "],", "];"]
(HERE / "fire-glyph.scad").write_text("\n".join(out) + "\n")
print(len(pts), f"aspect {(x1 - x0) / h:.3f}")
