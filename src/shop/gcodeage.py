"""Is a gcode on the printer older than the model it was sliced from?

The slice time is the slicer's header line (``; generated by OrcaSlicer 2.5.2 on 2026-11-23 at 14:48:37``),
never the printer's file date, which an upload or a tool-change strip resets. The model's change time
is the newest commit (or uncommitted edit) that changed a body's volume or extents, or added one.
A slicer-settings save, an object rename or bodies removed from the plate in the slicer do not count.
Both times are local wall-clock times on the assumption that the slicing box shares this box's zone.
"""

from __future__ import annotations

import re
import subprocess
import zipfile
from dataclasses import dataclass
from datetime import datetime
from io import BytesIO
from pathlib import Path

HEADER = re.compile(r"; generated by .*? on (\d{4}-\d\d-\d\d) at (\d\d:\d\d:\d\d)")
MESH = re.compile(r"<mesh>.*?</mesh>", re.S)
VERTEX = re.compile(r'<vertex x="([^"]+)" y="([^"]+)" z="([^"]+)"')
TRIANGLE = re.compile(r'<triangle v1="(\d+)" v2="(\d+)" v3="(\d+)"')
WALK = 40  # commits searched back for the last shape change


def sliced_at(header: str) -> datetime | None:
    m = HEADER.search(header)
    return datetime.fromisoformat(f"{m[1]}T{m[2]}") if m else None


def model_for(gcode: str, root: Path) -> Path | None:
    """The 3MF whose stem the gcode name starts with (Orca names a slice ``<stem>_<material>_<time>``); the longest wins."""
    hits = [p for p in root.glob("projects/*/out/*.3mf")
            if gcode == p.stem + ".gcode" or gcode.startswith(p.stem + "_")]
    return max(hits, key=lambda p: len(p.stem), default=None)


Body = tuple[float, tuple[float, float, float]]  # volume, sorted extents


def _match(a: Body, b: Body) -> bool:
    return abs(a[0] - b[0]) < 1.0 and all(abs(p - q) < 0.05 for p, q in zip(a[1], b[1]))


@dataclass(frozen=True)
class Shape:
    bodies: tuple[Body, ...]

    def same(self, older: Shape) -> bool:
        """True when this shape is ``older``'s, or ``older`` with bodies removed (a plate trimmed in the slicer)."""
        left = list(older.bodies)
        for b in self.bodies:
            hit = next((i for i, o in enumerate(left) if _match(b, o)), None)
            if hit is None:
                return False
            left.pop(hit)
        return True


def shape(data: bytes) -> Shape:
    """Volume and extents of every mesh in a 3MF."""
    bodies = []
    with zipfile.ZipFile(BytesIO(data)) as z:
        for name in sorted(n for n in z.namelist() if n.endswith(".model")):
            for mesh in MESH.findall(z.read(name).decode()):
                v = [tuple(map(float, t)) for t in VERTEX.findall(mesh)]
                if not v:
                    continue
                vol = 0.0
                for a, b, c in TRIANGLE.findall(mesh):
                    (x1, y1, z1), (x2, y2, z2), (x3, y3, z3) = v[int(a)], v[int(b)], v[int(c)]
                    vol += (x1 * (y2 * z3 - y3 * z2) - x2 * (y1 * z3 - y3 * z1) + x3 * (y1 * z2 - y2 * z1)) / 6
                ext = tuple(sorted(round(max(p[i] for p in v) - min(p[i] for p in v), 2) for i in range(3)))
                bodies.append((abs(vol), ext))
    return Shape(tuple(sorted(bodies)))


@dataclass
class Change:
    when: datetime
    what: str  # "<sha> <subject>" or "uncommitted edit"


def _git(root: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, check=True).stdout


def last_change(path: Path, root: Path) -> Change | None:
    """When the 3MF last changed shape: the working copy against origin/main's history (HEAD's when there is none)."""
    rel = path.relative_to(root).as_posix()
    try:
        ref = "origin/main" if _git(root, "rev-parse", "--verify", "-q", "origin/main").strip() else "HEAD"
    except subprocess.CalledProcessError:
        ref = "HEAD"
    log = [ln.split(" ", 2) for ln in _git(root, "log", f"-{WALK}", "--format=%H %ct %s", ref, "--", rel).splitlines()]
    if not log:
        return Change(datetime.fromtimestamp(path.stat().st_mtime), "uncommitted edit") if path.exists() else None

    def at(sha: str) -> Shape:
        return shape(subprocess.run(["git", "-C", str(root), "show", f"{sha}:{rel}"], capture_output=True, check=True).stdout)

    now = at(log[0][0])
    if path.exists() and not shape(path.read_bytes()).same(now):
        return Change(datetime.fromtimestamp(path.stat().st_mtime), "uncommitted edit")
    newest = log[0]
    for entry in log[1:]:
        if not now.same(at(entry[0])):
            break
        newest = entry
    sha, ct, subject = newest
    return Change(datetime.fromtimestamp(int(ct)), f"{sha[:7]} {subject}")


def verdict(gcode: str, header: str, root: Path) -> tuple[str, str]:
    """(level, text) for preflight: WARN when the model changed shape after the gcode was sliced."""
    sliced = sliced_at(header)
    model = model_for(gcode, root)
    if model is None:
        return "note", "gcode age unchecked: no projects/*/out/*.3mf matches its name"
    if sliced is None:
        return "WARN", f"gcode age unknown: no slicer header line; check it was sliced from {model.relative_to(root)}"
    change = last_change(model, root)
    if change is None:
        return "note", f"gcode age unchecked: {model.relative_to(root)} has no history"
    s, c = f"{sliced:%Y-%m-%d %H:%M}", f"{change.when:%Y-%m-%d %H:%M}"
    if change.when > sliced:
        return "WARN", (f"STALE GCODE: sliced {s}, but {model.relative_to(root)} changed shape after it, "
                        f"{c} ({change.what[:70]}). This file prints the old part. Re-slice in Orca and send it before starting")
    return "ok", f"gcode sliced {s}, after the model's last shape change {c}"
